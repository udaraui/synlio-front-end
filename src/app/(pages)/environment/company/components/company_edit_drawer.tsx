"use client";

import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { useState, useEffect } from "react";
import { z } from "zod";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { toast } from "sonner";
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from "@/components/ui/form";
import {
  Building2,
  Camera,
  Loader2,
  Save,
} from "lucide-react";
import { Avatar, AvatarFallback, AvatarImage } from "@/components/ui/avatar";
import { updateCompany, getCompanyById } from "@/services/company-management/company-services";
import { Company } from "@/interfaces/company";
import { API_URL } from "@/lib/constants";
import { ActiveStatus } from "@/interfaces/common/status.enum";
import { joinCompanyAddress, splitCompanyAddress } from "@/lib/company-address";
import { usePrivilegeGuard } from "@/hooks/use-privilege-guard";
import { cn } from "@/lib/utils";

interface CompanyEditDrawerProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onSubmit?: (data: any) => void;
  company?: Company;
  onCompanyUpdate?: () => void;
}

const formSchema = z.object({
  company: z.string().min(1, { message: "Company name is required." }),
  // Auto-generated by the backend and immutable — shown read-only.
  company_code: z.string().optional(),
  company_address: z.string().optional(),
  company_address_2: z.string().optional(),
  company_address_3: z.string().optional(),
  logo: z.instanceof(File).optional(),
  active_status: z.nativeEnum(ActiveStatus).optional(),
});

export function CompanyEditDrawer({
  open,
  onOpenChange,
  company,
  onCompanyUpdate,
  onSubmit: onSubmitCallback,
}: CompanyEditDrawerProps) {
  const canEditCompany = usePrivilegeGuard("2") as boolean;
  const [isSubmitting, setIsSubmitting] = useState(false);
  // false while the address is unknown (not in the list row and not yet fetched);
  // in that case it is not sent on save so an existing address is never wiped.
  const [addressLoaded, setAddressLoaded] = useState(true);

  const form = useForm({
    resolver: zodResolver(formSchema),
    defaultValues: {
      logo: undefined as File | undefined,
      company: company?.company,
      company_code: company?.company_code,
      company_address: splitCompanyAddress(company?.address)[0],
      company_address_2: splitCompanyAddress(company?.address)[1],
      company_address_3: splitCompanyAddress(company?.address)[2],
      active_status: (company?.isActive as ActiveStatus) || company?.active_status,
    },
  });

  useEffect(() => {
    if (open) {
      const [address1, address2, address3] = splitCompanyAddress(company?.address);
      form.reset({
        logo: undefined,
        company: company?.company,
        company_code: company?.company_code,
        company_address: address1,
        company_address_2: address2,
        company_address_3: address3,
        active_status: (company?.isActive as ActiveStatus) || company?.active_status,
      });

      if (company?.id && company.address === undefined) {
        setAddressLoaded(false);
        let cancelled = false;
        getCompanyById(company.id)
          .then((res) => {
            if (cancelled) return;
            const [a1, a2, a3] = splitCompanyAddress(res?.data?.address);
            form.setValue("company_address", a1);
            form.setValue("company_address_2", a2);
            form.setValue("company_address_3", a3);
            setAddressLoaded(true);
          })
          .catch(() => {});
        return () => {
          cancelled = true;
        };
      }
      setAddressLoaded(true);
    }
    return undefined;
  }, [open, company, form]);

  const onSubmit = async (data: any) => {
    setIsSubmitting(true);
    try {
      const payload = {
        id: company?.id as number,
        company: data.company,
        logo: canEditCompany ? data.logo : undefined,
        address: addressLoaded
          ? joinCompanyAddress(
              data.company_address,
              data.company_address_2,
              data.company_address_3,
            )
          : undefined,
        isActive: data.active_status,
      };
      const response = await updateCompany(payload);
      if (response.status === 200) {
        toast.success("Company updated");
        onOpenChange(false);
        form.reset();
        onCompanyUpdate?.();
        onSubmitCallback?.(response.data);
      } else {
        toast.error("Company update failed");
      }
    } catch (error: any) {
      console.error(error);
      toast.error("Failed to update company (" + (error?.message ?? "Unknown error") + ")");
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-[640px] max-h-[90vh] flex flex-col p-0 overflow-hidden border-none shadow-2xl">
        {/* Header */}
        <DialogHeader className="px-6 pt-5 sticky top-0 z-10 bg-background">
          <div className="flex items-center gap-3">
            <div>
              <DialogTitle className="text-lg">Edit Company</DialogTitle>
            </div>
          </div>
        </DialogHeader>

        {/* Scrollable body */}
        <Form {...form}>
          <form onSubmit={form.handleSubmit(onSubmit)} className="flex-1 flex flex-col overflow-hidden">
            <div className="flex-1 overflow-y-auto px-8">
              <div className="flex flex-col md:flex-row gap-8 items-start">
                {/* Logo with camera button */}
                <FormField
                  control={form.control}
                  name="logo"
                  render={({ field: { onChange, value, ...rest } }) => {
                    const isFileObject = value instanceof File;
                    const existingImageUrl =
                      company?.logo && !isFileObject
                        ? `${API_URL}/uploads/logos/${company.logo}`
                        : null;
                    const newFileUrl =
                      isFileObject && value ? URL.createObjectURL(value as File) : null;
                    const previewUrl = newFileUrl || existingImageUrl;
                    return (
                      <div className="flex flex-col items-center gap-2 flex-shrink-0 pt-2 cursor-pointer">
                        <div className="relative">
                          <Avatar className="h-24 w-24 border-2 border-background ring-1 ring-border">
                            <AvatarImage
                              src={previewUrl || undefined}
                              className="object-cover"
                            />
                            <AvatarFallback className="text-lg font-semibold bg-primary text-white">
                              <Building2 className="w-10 h-10" />
                            </AvatarFallback>
                          </Avatar>
                          <button
                            type="button"
                            disabled={!canEditCompany}
                            onClick={() => {
                              if (canEditCompany) {
                                document.getElementById("company-logo-edit")?.click();
                              }
                            }}
                            className={cn(
                              "absolute bottom-0 right-0 p-1.5 ring-1 rounded-full shadow-md transition-transform active:scale-95",
                              canEditCompany
                                ? "cursor-pointer bg-primary text-primary-foreground hover:bg-primary/90"
                                : "opacity-50 cursor-not-allowed bg-muted text-muted-foreground"
                            )}
                          >
                            <Camera className="w-4 h-4" />
                          </button>
                        </div>
                        <Input
                          type="file"
                          id="company-logo-edit"
                          accept="image/*"
                          className="hidden"
                          disabled={!canEditCompany}
                          onChange={(e) => {
                            if (!canEditCompany) return;
                            const file = e.target.files?.[0];
                            if (file) {
                              onChange(file);
                            }
                          }}
                          {...rest}
                        />
                      </div>
                    );
                  }}
                />

                <div className="flex-1 space-y-5 w-full">
                  {/* Name + Code */}
                  <div className="grid grid-cols-2 gap-5">
                    <FormField
                      control={form.control}
                      name="company"
                      render={({ field }) => (
                        <FormItem>
                          <FormLabel>Name</FormLabel>
                          <FormControl>
                            <Input placeholder="e.g. Acme Corporation" className="bg-muted/40" disabled={!canEditCompany} {...field} />
                          </FormControl>
                          <FormMessage />
                        </FormItem>
                      )}
                    />
                    <FormField
                      control={form.control}
                      name="company_code"
                      render={({ field }) => (
                        <FormItem>
                          <FormLabel>Code</FormLabel>
                          <FormControl>
                            <Input placeholder="Auto-generated" className="bg-muted/40" disabled {...field} value={field.value ?? ""} />
                          </FormControl>
                          <FormMessage />
                        </FormItem>
                      )}
                    />
                  </div>

                  {/* Address (optional) */}
                  <div className="space-y-3">
                    <FormField
                      control={form.control}
                      name="company_address"
                      render={({ field }) => (
                        <FormItem>
                          <FormLabel>
                            Address <span className="text-muted-foreground font-normal">(optional)</span>
                          </FormLabel>
                          <FormControl>
                            <Input placeholder="Address Line 1" className="bg-muted/40" {...field} value={field.value ?? ""} />
                          </FormControl>
                          <FormMessage />
                        </FormItem>
                      )}
                    />
                    <FormField
                      control={form.control}
                      name="company_address_2"
                      render={({ field }) => (
                        <FormItem>
                          <FormControl>
                            <Input placeholder="Address Line 2 (Suite, Floor, etc.)" className="bg-muted/40" {...field} value={field.value ?? ""} />
                          </FormControl>
                          <FormMessage />
                        </FormItem>
                      )}
                    />
                    <FormField
                      control={form.control}
                      name="company_address_3"
                      render={({ field }) => (
                        <FormItem>
                          <FormControl>
                            <Input placeholder="City, State, ZIP Code" className="bg-muted/40" {...field} value={field.value ?? ""} />
                          </FormControl>
                          <FormMessage />
                        </FormItem>
                      )}
                    />
                  </div>

                  {/* Status */}
                  <FormField
                    control={form.control}
                    name="active_status"
                    render={({ field }) => (
                      <FormItem>
                        <FormLabel>Status</FormLabel>
                        <Select value={field.value} onValueChange={field.onChange} disabled={!canEditCompany}>
                          <FormControl>
                            <SelectTrigger className="bg-muted/40" disabled={!canEditCompany}>
                              <SelectValue placeholder="Select status" />
                            </SelectTrigger>
                          </FormControl>
                          <SelectContent>
                            <SelectItem value={ActiveStatus.ACTIVE}>Active</SelectItem>
                            <SelectItem value={ActiveStatus.SUSPEND}>Suspend</SelectItem>
                            <SelectItem value={ActiveStatus.BLOCK}>Block</SelectItem>
                          </SelectContent>
                        </Select>
                        <FormMessage />
                      </FormItem>
                    )}
                  />
                </div>
              </div>
            </div>

            {/* Footer */}
            <DialogFooter className="px-8 pb-6 pt-4">
              <Button
                type="button"
                variant="outline"
                onClick={() => onOpenChange(false)}
              >
                Cancel
              </Button>
              <Button type="submit" disabled={isSubmitting}>
                {isSubmitting ? (
                  <Loader2 className="h-4 w-4 animate-spin" />
                ) : (
                  <Save className="h-4 w-4" />
                )}
                Update
              </Button>
            </DialogFooter>
          </form>
        </Form>
      </DialogContent>
    </Dialog>
  );
}

export default CompanyEditDrawer;
